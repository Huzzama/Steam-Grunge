"""
artwork_pack.py — Steam artwork on a USB stick (or any file) instead of Drive.

Export writes ONE zip:

    steam-artwork-<steamid>.zip
    ├── artwork-pack.json          {"format": 1, "steam_id": …, "created": …}
    ├── grid/…                     Steam/userdata/<steamid>/config/grid/   (custom artwork)
    └── librarycache/…             Steam/appcache/librarycache/            (Steam's own cache)

Import accepts, in order of detection:
    • a zip in that layout (either folder may be missing),
    • a Drive backup zip (steam-grid-<id>.zip — grid files at the root),
    • a folder: grid/ + librarycache/ side by side, or a bare grid folder,
      or a bare librarycache folder (recognised by its contents).

Files with the same name are overwritten; nothing is ever written outside
the two Steam folders (zip-slip guard). librarycache is Steam's cache — it is
regenerated by Steam, so importing it only "pre-loads" artwork; the grid
folder is what Steam treats as the user's choice. Steam reads both on
restart (the caller offers steamSync.restart_steam()).

Everything here is blocking — run it on a worker thread.
"""
from __future__ import annotations

import json
import re
import time
import zipfile
from pathlib import Path
from typing import Callable, Optional

from app import config as _cfg

PACK_META   = "artwork-pack.json"
PACK_FORMAT = 1
GRID_DIR    = "grid"
CACHE_DIR   = "librarycache"

Progress = Optional[Callable[[str], None]]

# A grid file: 12345p.png, 12345.png, 12345_hero.png, 12345_logo.png, 12345_icon.jpg …
_GRID_FILE  = re.compile(r"^\d+(p|_hero|_logo|_icon)?\.(png|jpe?g|webp|ico|gif)$", re.I)
# A librarycache entry: a numeric per-app folder, or the old flat 12345_library_600x900.jpg
_CACHE_FLAT = re.compile(r"^\d+_(library_600x900|library_hero|header|logo|icon)[^/]*$", re.I)


# ── Steam folders ──────────────────────────────────────────────────────────────

def steam_folders(steam_id: str) -> tuple[Path, Path]:
    """(grid, librarycache) for *steam_id*. Raises if Steam is not found."""
    from app.services.steamSync import find_steam_userdata, get_grid_folder
    userdata = find_steam_userdata()
    if not userdata:
        raise RuntimeError("Steam installation not found.")
    grid  = get_grid_folder(userdata, steam_id)
    cache = userdata.parent / "appcache" / "librarycache"
    return grid, cache


def _files_under(root: Path) -> list[Path]:
    if not root.is_dir():
        return []
    return [p for p in sorted(root.rglob("*")) if p.is_file()]


def folder_stats(root: Path) -> tuple[int, int]:
    """(file count, total bytes) — for the size hints in the export dialog."""
    files = _files_under(root)
    return len(files), sum(p.stat().st_size for p in files)


def default_pack_name(steam_id: str) -> str:
    return f"steam-artwork-{steam_id}.zip"


# ── Export ─────────────────────────────────────────────────────────────────────

def export_pack(steam_id: str, dest: Path, *, include_grid: bool = True,
                include_cache: bool = True, on_progress: Progress = None) -> dict:
    """
    Write the pack to *dest*. Images do not compress, so the zip is stored
    (fast, and fine for a USB stick). Returns {"ok", "files", "bytes", "error"}.
    """
    try:
        grid, cache = steam_folders(steam_id)
        parts: list[tuple[str, Path]] = []
        if include_grid:
            parts.append((GRID_DIR, grid))
        if include_cache:
            parts.append((CACHE_DIR, cache))
        plan = [(name, root, p) for name, root in parts for p in _files_under(root)]
        if not plan:
            return {"ok": False, "files": 0, "bytes": 0,
                    "error": "Nothing to export — the selected folders are empty."}

        dest = Path(dest)
        dest.parent.mkdir(parents=True, exist_ok=True)
        tmp = dest.with_name(dest.name + ".part")
        total = len(plan)
        with zipfile.ZipFile(tmp, "w", zipfile.ZIP_STORED, allowZip64=True) as zf:
            zf.writestr(PACK_META, json.dumps({
                "format":   PACK_FORMAT,
                "steam_id": steam_id,
                "created":  time.strftime("%Y-%m-%dT%H:%M:%S"),
                "app":      f"Steam Grunge Editor {_app_version()}",
                "contents": [name for name, _ in parts],
            }, indent=2))
            for i, (name, root, p) in enumerate(plan, 1):
                zf.write(p, f"{name}/{p.relative_to(root).as_posix()}")
                if on_progress and (i % 50 == 0 or i == total):
                    on_progress(f"Packing {i}/{total}…")
        tmp.replace(dest)
        return {"ok": True, "files": total, "bytes": dest.stat().st_size, "error": None}
    except Exception as e:
        return {"ok": False, "files": 0, "bytes": 0, "error": str(e)}


# ── Import ─────────────────────────────────────────────────────────────────────

def _classify_zip(zf: zipfile.ZipFile) -> dict[str, str]:
    """
    Map each zip member to its target ("grid" / "librarycache") by the layout:
    pack zips carry the folder as the first path segment, Drive backups keep
    grid files at the root.
    """
    out: dict[str, str] = {}
    names = [m.filename for m in zf.infolist() if not m.is_dir()]
    packed = any(n.startswith((f"{GRID_DIR}/", f"{CACHE_DIR}/")) for n in names)
    for n in names:
        if n == PACK_META:
            continue
        if packed:
            head, _, _rest = n.partition("/")
            if head in (GRID_DIR, CACHE_DIR):
                out[n] = head
        else:
            out[n] = GRID_DIR          # Drive backup: everything is grid
    return out


def classify_folder(folder: Path) -> dict[str, Path]:
    """
    Which Steam folder(s) a user-picked folder feeds:
      {"grid": <path>, "librarycache": <path>} — any subset; empty = unknown.
    """
    folder = Path(folder)
    out: dict[str, Path] = {}
    if (folder / GRID_DIR).is_dir() or (folder / CACHE_DIR).is_dir():
        if (folder / GRID_DIR).is_dir():
            out[GRID_DIR] = folder / GRID_DIR
        if (folder / CACHE_DIR).is_dir():
            out[CACHE_DIR] = folder / CACHE_DIR
        return out
    name = folder.name.lower()
    entries = list(folder.iterdir()) if folder.is_dir() else []
    if name == GRID_DIR or any(_GRID_FILE.match(e.name) for e in entries if e.is_file()):
        out[GRID_DIR] = folder
    elif name == CACHE_DIR or any(e.is_dir() and e.name.isdigit() for e in entries) \
            or any(_CACHE_FLAT.match(e.name) for e in entries if e.is_file()):
        out[CACHE_DIR] = folder
    return out


def _safe_target(root: Path, rel: str) -> Optional[Path]:
    target = (root / rel).resolve()
    return target if root.resolve() in target.parents else None


def import_pack(source: Path, steam_id: str, *, on_progress: Progress = None) -> dict:
    """
    Copy artwork from a zip or folder into Steam. Returns
    {"ok", "grid": n, "librarycache": n, "skipped": n, "error"}.
    """
    try:
        source = Path(source)
        grid, cache = steam_folders(steam_id)
        roots = {GRID_DIR: grid, CACHE_DIR: cache}
        written = {GRID_DIR: 0, CACHE_DIR: 0}
        skipped = 0

        if source.is_file():
            with zipfile.ZipFile(source) as zf:
                plan = _classify_zip(zf)
                if not plan:
                    return {"ok": False, "grid": 0, "librarycache": 0, "skipped": 0,
                            "error": "This zip holds no grid/ or librarycache/ artwork."}
                total = len(plan)
                for i, (member, kind) in enumerate(plan.items(), 1):
                    rel = member.split("/", 1)[1] if member.startswith(f"{kind}/") else member
                    target = _safe_target(roots[kind], rel)
                    if target is None:
                        skipped += 1
                        continue
                    target.parent.mkdir(parents=True, exist_ok=True)
                    with zf.open(member) as src, open(target, "wb") as dst:
                        dst.write(src.read())
                    written[kind] += 1
                    if on_progress and (i % 50 == 0 or i == total):
                        on_progress(f"Importing {i}/{total}…")
        elif source.is_dir():
            plan_dirs = classify_folder(source)
            if not plan_dirs:
                return {"ok": False, "grid": 0, "librarycache": 0, "skipped": 0,
                        "error": "Could not tell what this folder is. Pick Steam's grid folder, "
                                 "its librarycache folder, or a folder holding both."}
            files = [(kind, root, p) for kind, root in plan_dirs.items() for p in _files_under(root)]
            total = len(files)
            for i, (kind, root, p) in enumerate(files, 1):
                if p.name == PACK_META:
                    continue
                target = _safe_target(roots[kind], p.relative_to(root).as_posix())
                if target is None or target == p:
                    skipped += 1
                    continue
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(p.read_bytes())
                written[kind] += 1
                if on_progress and (i % 50 == 0 or i == total):
                    on_progress(f"Importing {i}/{total}…")
        else:
            return {"ok": False, "grid": 0, "librarycache": 0, "skipped": 0,
                    "error": f"{source} does not exist."}

        if written[GRID_DIR] + written[CACHE_DIR] == 0:
            return {"ok": False, "grid": 0, "librarycache": 0, "skipped": skipped,
                    "error": "No artwork files were imported."}
        return {"ok": True, "grid": written[GRID_DIR], "librarycache": written[CACHE_DIR],
                "skipped": skipped, "error": None}
    except Exception as e:
        return {"ok": False, "grid": 0, "librarycache": 0, "skipped": 0, "error": str(e)}


def _app_version() -> str:
    try:
        return (Path(_cfg.ASSETS_DIR).parent.parent / "VERSION").read_text(encoding="utf-8").strip()
    except Exception:
        return "?"
